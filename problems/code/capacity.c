  clock_t t0=clock();build();
  printf("table: %ld subspaces (expect 8283458), %.1fs\n",nins,(double)(clock()-t0)/CLOCKS_PER_SEC);
  spans=malloc(sizeof(BM)*MAXS);sk1=malloc(8u<<22);
  // sanity: Prop 2.2
  for(int u=1;u<512;u++){int v[1]={u};BM b;spanbm(v,1,&b);if(hget(&b)!=19){printf("dim1 mismatch\n");}}
  printf("dim1 all L=19 checked\n");
  // positive controls: first factors of flip-graph 23-term schemes
  const char* mode=argc>1?argv[1]:"control";
