// Capacity oracle for <3,3,3> over F2 from Wang's certificate + profile experiments.
// Convention: first factor u is a 9-bit functional on A=M3(F2), bit 3i+j <-> U_ij.
// cap_r(E) = r - L(E) where L is indexed by E = S^perp (the certificate's "constraints").
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

typedef struct { uint64_t w[8]; } BM; // 512-bit set of vectors
static inline void bset(BM*b,int v){b->w[v>>6]|=1ULL<<(v&63);}
static inline int bget(const BM*b,int v){return b->w[v>>6]>>(v&63)&1;}

// ---------- matrices over F2 ----------
static int mmul(int A,int B){int C=0;for(int i=0;i<3;i++)for(int j=0;j<3;j++){int s=0;for(int k=0;k<3;k++)s^=(A>>(3*i+k)&1)&(B>>(3*k+j)&1);C|=s<<(3*i+j);}return C;}
static int mtr(int A){int C=0;for(int i=0;i<3;i++)for(int j=0;j<3;j++)if(A>>(3*i+j)&1)C|=1<<(3*j+i);return C;}
static int mrank(int A){int r[3]={A&7,A>>3&7,A>>6&7},rk=0;for(int c=0;c<3;c++){int p=-1;for(int i=rk;i<3;i++)if(r[i]>>c&1){p=i;break;}if(p<0)continue;int t=r[p];r[p]=r[rk];r[rk]=t;for(int i=0;i<3;i++)if(i!=rk&&(r[i]>>c&1))r[i]^=r[rk];rk++;}return rk;}
static int GL[168],nGL;
#define NG (168*168*2)
static uint16_t *act; // act[g*512+u]

// ---------- hash table: span bitmap -> L ----------
#define HB 25
#define HS (1u<<HB)
static uint64_t *hk1,*hk2; static int8_t *hv;
static inline void hashbm(const BM*b,uint64_t*h1,uint64_t*h2){uint64_t a=0x9E3779B97F4A7C15ULL,c=0xC2B2AE3D27D4EB4FULL;for(int i=0;i<8;i++){a^=b->w[i];a*=0xff51afd7ed558ccdULL;a^=a>>33;c+=b->w[i]*0x94D049BB133111EBULL;c^=c>>29;c*=0xBF58476D1CE4E5B9ULL;}*h1=a|1;*h2=c;}
static long nins=0;
static void hput(const BM*b,int v){uint64_t h1,h2;hashbm(b,&h1,&h2);uint32_t i=h1&(HS-1);while(hk1[i]){if(hk1[i]==h1&&hk2[i]==h2){if(hv[i]!=v){fprintf(stderr,"conflict\n");exit(1);}return;}i=(i+1)&(HS-1);}hk1[i]=h1;hk2[i]=h2;hv[i]=v;nins++;}
static int hget(const BM*b){uint64_t h1,h2;hashbm(b,&h1,&h2);uint32_t i=h1&(HS-1);while(hk1[i]){if(hk1[i]==h1&&hk2[i]==h2)return hv[i];i=(i+1)&(HS-1);}return -1;}
static void spanbm(const int*v,int d,BM*b){memset(b,0,sizeof *b);int cur=0;bset(b,0);for(int m=1;m<(1<<d);m++){int bit=__builtin_ctz(m);cur^=v[bit];bset(b,cur);}}

static void build(void){
  for(int A=0;A<512;A++)if(mrank(A)==3)GL[nGL++]=A;
  act=malloc((size_t)NG*512*2);
  int g=0;for(int p=0;p<168;p++)for(int q=0;q<168;q++)for(int t=0;t<2;t++,g++)for(int u=0;u<512;u++){int U=t?mtr(u):u;act[(size_t)g*512+u]=mmul(mmul(GL[p],U),GL[q]);}
  hk1=calloc(HS,8);hk2=calloc(HS,8);hv=calloc(HS,1);
  FILE*f=fopen("orbits.txt","r");int lb,d;
  while(fscanf(f,"%d %d",&lb,&d)==2){int v[9];for(int i=0;i<d;i++)fscanf(f,"%d",&v[i]);
    for(int g2=0;g2<NG;g2++){int w[9];for(int i=0;i<d;i++)w[i]=act[(size_t)g2*512+v[i]];BM b;spanbm(w,d,&b);hput(&b,lb);}}
  fclose(f);
}

// ---------- profile check over all spans generated by the profile ----------
// returns 1 if admissible at r; prints first violation if verbose
#define MAXS 2000000
static BM *spans; static int nsp;
static uint64_t *sk1; // dedupe set for spans
static int sseen(const BM*b){uint64_t h1,h2;hashbm(b,&h1,&h2);uint32_t m=(1u<<22)-1,i=h1&m;while(sk1[i]){if(sk1[i]==h1)return 1;i=(i+1)&m;}sk1[i]=h1;return 0;}
static int check(const int*P,int n,int r,int verbose,int*tight){
  memset(sk1,0,8u<<22);nsp=0;BM z;memset(&z,0,sizeof z);bset(&z,0);spans[nsp++]=z;sseen(&z);
  for(int k=0;k<n;k++){int v=P[k];int cur=nsp;
    for(int s=0;s<cur;s++){if(bget(&spans[s],v))continue;BM nb=spans[s];for(int u=0;u<512;u++)if(bget(&spans[s],u))bset(&nb,u^v);
      if(!sseen(&nb)){if(nsp>=MAXS){fprintf(stderr,"too many spans\n");exit(1);}spans[nsp++]=nb;}}}
  int ok=1;if(tight)*tight=0;
  for(int s=1;s<nsp;s++){int c=0;for(int k=0;k<n;k++)c+=bget(&spans[s],P[k]);int L=hget(&spans[s]);if(L<0){fprintf(stderr,"lookup miss\n");exit(1);}
    if(c>r-L){ok=0;if(verbose){int d=0;for(int u=0;u<512;u++)d+=bget(&spans[s],u);printf("  violation: |E|=%d count=%d cap=%d\n",d,c,r-L);}if(!verbose)return 0;}
    else if(c==r-L&&tight)(*tight)++;}
  return ok;}


static int cost(const int*P,int n,int r){
  memset(sk1,0,8u<<22);nsp=0;BM z;memset(&z,0,sizeof z);bset(&z,0);spans[nsp++]=z;sseen(&z);
  for(int k=0;k<n;k++){int v=P[k];int cur=nsp;
    for(int s=0;s<cur;s++){if(bget(&spans[s],v))continue;BM nb=spans[s];for(int u=0;u<512;u++)if(bget(&spans[s],u))bset(&nb,u^v);
      if(!sseen(&nb)){if(nsp>=MAXS){fprintf(stderr,"too many spans\n");exit(1);}spans[nsp++]=nb;}}}
  int tot=0;for(int s=1;s<nsp;s++){int c=0;for(int k=0;k<n;k++)c+=bget(&spans[s],P[k]);int L=hget(&spans[s]);if(c>r-L)tot+=c-(r-L);}
  return tot;}
static uint64_t rs[2]={1,2};static inline uint64_t rnd(void){uint64_t s1=rs[0];const uint64_t s0=rs[1];rs[0]=s0;s1^=s1<<23;rs[1]=s1^s0^(s1>>17)^(s0>>26);return rs[1]+s0;}

